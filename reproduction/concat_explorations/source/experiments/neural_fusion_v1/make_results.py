"""Generate reports/neural_fusion_v1/RESULTS.md from run_summary.json files.

Only reads artifacts the runs actually produced; a model/split/seed with no run is
reported as missing rather than estimated.

    env -u PYTHONPATH ../../.venv/bin/python make_results.py
"""
from __future__ import annotations

import json
from pathlib import Path

from config import REPORT, SPLITS

MODEL_ORDER = ["mlp", "static_transformer", "lstm_concat", "lstm_transformer"]
MODE_ORDER = {"full": 0, "probe": 1, "smoke": 2}


def load_runs() -> list[dict]:
    runs = []
    for path in sorted((REPORT / "runs").iterdir()):
        summary = path / "run_summary.json"
        if not summary.exists():
            meta = path / "run_metadata.json"
            runs.append({"run_id": path.name, "incomplete": True,
                         "mode": (json.loads(meta.read_text()).get("mode") if meta.exists() else "?"),
                         "reason": "run_summary.json absent (crashed or still running)"})
            continue
        payload = json.loads(summary.read_text())
        payload["incomplete"] = False
        meta = path / "run_metadata.json"
        if meta.exists():
            payload["invalidated"] = json.loads(meta.read_text()).get("invalidated")
        runs.append(payload)
    return runs


def table(header: list[str], body: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join(["---"] * len(header)) + "|"]
    for row in body:
        lines.append("| " + " | ".join(str(cell) for cell in row) + " |")
    return "\n".join(lines)


def fmt(value, digits=2):
    return "—" if value is None else f"{value:.{digits}f}"


def main() -> None:
    runs = load_runs()
    complete = [r for r in runs if not r.get("incomplete")]
    checks = {}
    for run in complete:
        for check in run.get("checkpoint_verification", []):
            checks[(run["run_id"], check["split_id"], check["model"], check["seed"])] = check

    lines = ["# neural_fusion_v1 — generated results", "",
             "Auto-generated by `make_results.py` from `runs/*/run_summary.json`.", ""]

    lines += ["## Run inventory", ""]
    inventory = []
    for run in runs:
        if run.get("incomplete"):
            inventory.append([run["run_id"], run.get("mode", "?"), "INCOMPLETE",
                              run.get("reason", ""), "—", "—"])
            continue
        flag = run.get("invalidated")
        status = "VALID" if not flag else flag.get("status", "FLAGGED")
        inventory.append([run["run_id"], run["mode"], status, len(run["results"]),
                          ", ".join(run["splits"]), ", ".join(map(str, run["seeds"])),
                          run.get("finished", "")])
    lines.append(table(["run_id", "mode", "status", "results", "splits", "seeds", "finished"], inventory))
    lines.append("")
    flagged = [run for run in complete if run.get("invalidated")]
    if flagged:
        lines += ["> `INVALID_GROUP_SEMANTICS` = produced before the numeric-group column-map fix;",
                  "> its numbers depend on incorrect feature assignment and must not be cited.",
                  "> `SUPERSEDED_PER_COLUMN_LAYOUT` = earlier encoder layout; the grouping bug never",
                  "> applied, but the run is kept for provenance only.", ""]

    if not complete:
        lines += ["No completed run yet — nothing to report.", ""]
        (REPORT / "RESULTS.md").write_text("\n".join(lines), encoding="utf-8")
        print("wrote RESULTS.md (no completed runs)")
        return

    lines += ["## Overall validation RMSE (SGD), original split", ""]
    orig = [r for run in complete for r in run["results"] if r["split_id"] == "orig"]
    orig.sort(key=lambda r: (MODE_ORDER.get(r["mode"], 9), MODEL_ORDER.index(r["model"]), r["seed"]))
    rows = []
    for r in orig:
        check = checks.get((r["run_id"], r["split_id"], r["model"], r["seed"]))
        rows.append([
            r["run_id"], r["model"], r["mode"], r["seed"], fmt(r["overall"]["rmse_sgd"]),
            fmt(r["overall"]["mae_sgd"]), fmt(r["overall"]["bias_sgd"], 1),
            r["overall"]["n"], r["n_parameters"], r["stage_a_selected_epochs"],
            fmt(r["stage_a_best_inner_rmse_sgd"]), r["total_seconds"],
            "ok" if check and check.get("ok") else ("—" if check is None else "FAIL"),
        ])
    lines.append(table(["run_id", "model", "mode", "seed", "RMSE", "MAE", "bias", "n",
                              "params", "epochs", "stage-A inner", "s", "ckpt"], rows))
    lines.append("")
    lines += ["Reference: saved LightGBM spatial benchmark = **477.2036** RMSE on the same",
              "35,158 rows. Neural numbers are `anchor + residual`; the tree model has no anchor.",
              ""]

    lines += ["## By horizon band, original split", "",
              "Empty bands are printed as `n=0`, not omitted.", ""]
    for run in complete:
        for r in run["results"]:
            if r["split_id"] != "orig":
                continue
            bands = ", ".join(f"{b['horizon_band']}: "
                              f"{'n=0' if b['n'] == 0 else fmt(b['rmse_sgd'])}"
                              for b in r["by_horizon_band"])
            lines.append(f"- `{r['run_id']}` / {r['model']} / seed {r['seed']} / {r['mode']} — {bands}")
    lines.append("")

    lines += ["## Every split", ""]
    rows = []
    for run in complete:
        for r in run["results"]:
            rows.append([r["run_id"], r["split_id"], r["model"], r["mode"], r["seed"],
                         fmt(r["overall"]["rmse_sgd"]), fmt(r["overall"]["bias_sgd"], 1),
                         r["overall"]["n"], r["validation_months"][0], r["validation_months"][1]])
    rows.sort(key=lambda row: (list(SPLITS).index(row[1]), MODEL_ORDER.index(row[2]), row[3], row[4], row[0]))
    lines.append(table(["run_id", "split", "model", "mode", "seed", "RMSE", "bias", "n", "from", "to"], rows))
    lines.append("")

    lines += ["## Seeds per model/split", ""]
    lines += ["Seeds are only pooled **within one run_id**: different runs may use a different",
              "design (e.g. `probe-r2` predates the causal-anchor target), so pooling them would",
              "report a design change as seed noise.", ""]
    grouped: dict[tuple[str, str, str, str], list[float]] = {}
    for run in complete:
        for r in run["results"]:
            grouped.setdefault((r["run_id"], r["split_id"], r["model"], r["mode"]), []).append(r["overall"]["rmse_sgd"])
    rows = []
    for (run_id, split, model, mode), values in sorted(grouped.items(), key=lambda kv: (kv[0][0], list(SPLITS).index(kv[0][1]), MODEL_ORDER.index(kv[0][2]), kv[0][3])):
        mean = sum(values) / len(values)
        spread = (max(values) - min(values)) if len(values) > 1 else None
        rows.append([run_id, split, model, mode, len(values), fmt(mean), fmt(min(values)), fmt(max(values)),
                     fmt(spread) if spread is not None else "single seed"])
    lines.append(table(["run_id", "split", "model", "mode", "n seeds", "mean", "min", "max", "spread"], rows))
    lines.append("")

    lines += ["## Checkpoint verification", ""]
    rows = [[key[0], key[1], key[2], key[3], "ok" if c.get("ok") else "FAIL",
             c.get("max_abs_delta_sgd")] for key, c in sorted(checks.items())]
    lines.append(table(["run_id", "split", "model", "seed", "result", "max |delta| SGD"], rows) if rows
                 else "No checkpoint verification was requested in any completed run.")
    lines.append("")
    lines += ["## Coverage gaps", "",
              "Model/split combinations with no completed run are listed here explicitly.", ""]
    rows = []
    for split in SPLITS:
        for model in MODEL_ORDER:
            present = sorted({r["seed"] for run in complete for r in run["results"]
                              if r["split_id"] == split and r["model"] == model and r["mode"] == "full"})
            rows.append([split, model, len(present), ", ".join(map(str, present)) or "NOT RUN"])
    lines.append(table(["split", "model", "full-mode seeds", "seeds"], rows))
    lines.append("")
    lines += ["## Pending work", "",
              "- Additional seeds for the original split, then the `early` and `long` splits.",
              "- Any row whose `mode` is `probe` or `smoke` is exploratory only; it is not an",
              "  architecture conclusion and is not comparable to a `full` row.",
              ""]

    (REPORT / "RESULTS.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote RESULTS.md from {len(complete)} completed run(s), {len(runs) - len(complete)} incomplete")


if __name__ == "__main__":
    main()
