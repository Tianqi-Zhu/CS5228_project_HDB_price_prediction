# Per-row vs per-window split: the market arrays are stored once per distinct window and
# referenced by `window_id`, so a batch must gather with that index rather than assume the
# market row order matches the sample order.
WINDOW_SHARING = ("market arrays are keyed by window_id; identical (target_month) rows "
                  "share one window. Batching must index with window_id.")

# --------------------------------------------------------------------------- statistics arm
# Calendar-window statistics. `mean3` is the mean over CALENDAR months t-3..t-1 and
# `recent3_minus_prior3` compares t-3..t-1 against t-6..t-4. These are not "the last three
# observations": stretching a window across a gap would report a different quantity than the
# name promises, and would disagree with any consumer computing calendar windows itself.
STATS_SUFFIXES = [
    "last_valid",
    "mean3",
    "mean12",
    "recent3_minus_prior3",
    "n_valid",
    "months_since_last_valid",
]


def stats_feature_names() -> list[str]:
    return [f"{channel}__{suffix}"
            for channel in MARKET_CHANNEL_ORDER for suffix in STATS_SUFFIXES]


