"""Schema for the target-month as-of v8 dataset.

This file is written **before** the arrays so the neural side can build its loader against
a stable contract. It is generated by `build.py` (never hand-edited) and is frozen together
with the arrays.

Design rules encoded here (see `docs/plans/2026-10-26-target-asof-bilstm-v8.md`):

* **One sample per transaction.** No random horizon, no multi-origin duplication, no rows
  dropped because their history is short. A transaction approved in month `t` is one sample
  whose target is `t`.
* **No rent history, no anchor.** Only static property attributes and external market series.
  `hist_*`, `context.anchor_*`, and every rent-derived statistic are excluded by construction.
* **The window is calendar months `[t-12, ..., t-1]`, oldest to newest.** Nothing from month
  `t` or later may enter, for any channel.
* **Target is `MONTHLY_RENT / 1000`**, reconstructed by `* 1000`. No log, no anchor offset,
  no output clipping.
* **Missing is masked, not zero.** Each channel carries an observation mask, and the window
  carries a step-valid mask so leading padding is distinguishable from an interior gap.
"""

