# --------------------------------------------------------------------------- market branch
# Calendar window length, oldest -> newest, covering months t-12 .. t-1 inclusive.
WINDOW_MONTHS = 12

# DBS D05.SI: three channels per month.
DBS_CHANNELS = [
    "dbs_log_return",
    "dbs_daily_vol_std",
    "dbs_log1p_volume",
]

# COE: four categories (a, b, c, e) x three channels.
COE_CATEGORIES = ["a", "b", "c", "e"]
COE_CHANNEL_TEMPLATES = [
    "coe_{cat}_premium_mean",
    "coe_{cat}_quota_total",
    "coe_{cat}_bids_over_quota",
]


def market_channel_names() -> list[str]:
    names = list(DBS_CHANNELS)
    for cat in COE_CATEGORIES:
        for template in COE_CHANNEL_TEMPLATES:
            names.append(template.format(cat=cat))
    return names


MARKET_CHANNEL_ORDER = market_channel_names()

