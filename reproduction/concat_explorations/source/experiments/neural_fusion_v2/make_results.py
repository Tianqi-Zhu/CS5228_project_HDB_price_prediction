"""Generate reports/neural_fusion_v2/RESULTS.md from run_summary.json files.

Only reports what runs actually produced. A model/split/seed without a run is listed as
not run. Superseded contracts and non-Gate-1 runs are labelled from the run's own
``result_status``; nothing is upgraded to a result by presence in the directory.

    env -u PYTHONPATH ../../.venv/bin/python make_results.py
"""
from __future__ import annotations

import json
from pathlib import Path

from .settings import REPORT_ROOT

CONTROLS = ["mlp", "static_transformer", "lstm_concat", "lstm_fusion"]
MODE_ORDER = {"full": 0, "probe": 1, "smoke": 2}
VALID_STATUS = {"REAL_CONTRACT"}


def load_runs() -> list[dict]:
    runs = []
    base = REPORT_ROOT / "runs"
    if not base.exists():
        return runs
    for path in sorted(base.iterdir()):
        if not path.is_dir():
            continue          # e.g. runs/README.md
        summary = path / "run_summary.json"
        meta = path / "run_manifest.json"
        if not summary.exists():
            runs.append({"run_id": path.name, "incomplete": True,
                         "mode": (json.loads(meta.read_text()).get("mode") if meta.exists() else "?"),
                         "reason": "run_summary.json absent"})
            continue
        payload = json.loads(summary.read_text())
        payload["incomplete"] = False
        runs.append(payload)
    return runs


def table(header: list[str], body: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join(["---"] * len(header)) + "|"]
    for row in body:
        lines.append("| " + " | ".join(str(cell) for cell in row) + " |")
    return "\n".join(lines)


def fmt(value, digits=2):
    return "—" if value is None else f"{value:.{digits}f}"


def main() -> None:
    runs = load_runs()
    complete = [r for r in runs if not r.get("incomplete")]
    lines = ["# neural_fusion_v2 — generated results", "",
             "Auto-generated by `make_results.py`. Read `result_status` before citing a number:",
             "only `REAL_CONTRACT` runs on the current contract are Gate 1 candidates.", ""]

    lines += ["## Run inventory", ""]
    body = []
    for run in runs:
        if run.get("incomplete"):
            body.append([run["run_id"], run.get("mode", "?"), "INCOMPLETE",
                         run.get("reason", ""), "—"])
            continue
        body.append([run["run_id"], run.get("mode"), run.get("result_status", "?"),
                     run.get("contract_id", "?"), len(run.get("results", []))])
    lines.append(table(["run_id", "mode", "result_status", "contract", "results"], body))
    lines.append("")

    current = [r for r in complete
               if r.get("result_status") in VALID_STATUS and r.get("contract_id", "").startswith(
                   "fusion-contract-v2.1.0")]
    stale = [r for r in complete if r not in current]
    if stale:
        lines += ["> Runs not listed below use a superseded contract or carry a non-Gate-1",
                  "> status; they are integration records only:", ""]
        for run in stale:
            lines.append(f"> - `{run['run_id']}` — {run.get('result_status')} "
                         f"({run.get('contract_id')})")
        lines.append("")

    if not current:
        lines += ["No Gate 1 run on the current contract yet.", ""]
        (REPORT_ROOT / "RESULTS.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
        print("wrote RESULTS.md (no current-contract runs)")
        return

    lines += ["## Original split, seed 42 (current contract)", ""]
    body = []
    for run in sorted(current, key=lambda r: MODE_ORDER.get(r.get("mode"), 9)):
        for r in run.get("results", []):
            if r["split"] != "orig":
                continue
            bands = {b["horizon_band"]: b for b in r["by_horizon_band"]}
            body.append([
                run["run_id"], r["control"], run.get("mode"), r["seed"],
                fmt(r["overall"]["rmse_sgd"]), fmt(r["overall"]["mae_sgd"], 1),
                fmt(r["overall"]["bias_sgd"], 1), r["overall"]["n"],
                r["n_parameters"], r["chosen_epochs"],
                fmt(r["stage_a_best_holdout_rmse_sgd"]),
                "n=0" if bands["13-16"]["n"] == 0 else fmt(bands["13-16"]["rmse_sgd"]),
            ])
    body.sort(key=lambda row: (MODE_ORDER.get(row[2], 9), CONTROLS.index(row[1])))
    lines.append(table(["run_id", "control", "mode", "seed", "RMSE", "MAE", "bias", "n",
                        "params", "epochs", "A/holdout RMSE", "13-16"], body))
    lines.append("")

    lines += ["## Parity and boundaries", "",
              "Every control must share byte-identical non-sequence inputs. One unique",
              "signature per stage means that held.", ""]
    body = []
    for run in current:
        results = run.get("results", [])
        if not results:
            continue
        b = results[0].get("boundaries", {})
        body.append([
            run["run_id"], run.get("mode"),
            len({r["parity_signature_B_fit"] for r in results}),
            len({r["parity_signature_B_validation"] for r in results}),
            b.get("populations", {}).get("A/fit"), b.get("populations", {}).get("A/holdout"),
            b.get("populations", {}).get("B/fit"), b.get("populations", {}).get("B/validation"),
            len(run.get("contract_deviations", [])),
        ])
    lines.append(table(["run_id", "mode", "unique B/fit sig", "unique B/val sig",
                        "A/fit", "A/holdout", "B/fit", "B/validation", "deviations"], body))
    lines.append("")

    lines += ["## Scaler provenance", "",
              "Each stage's state must be fitted on its own `fit` population.", ""]
    body = [[run["run_id"], r["control"], r["stage_a_scaler_fitted_on"],
             r["stage_b_scaler_fitted_on"]]
            for run in current for r in run.get("results", [])]
    lines.append(table(["run_id", "control", "stage A fitted on", "stage B fitted on"], body))
    lines.append("")

    lines += ["## Actual parameters", ""]
    seen = set()
    body = []
    for run in current:
        for r in run.get("results", []):
            if r["control"] in seen:
                continue
            seen.add(r["control"])
            m = r["actual_manifest"]
            body.append([r["control"], m["capacity"]["d_model"], m["capacity"]["layers"],
                         m["capacity"]["heads"], m["capacity"]["lstm_hidden"],
                         m["shapes"]["static_dim"], m["shapes"]["history_dim"],
                         m["shapes"]["context_dim"], m["shapes"]["sequence_channels"],
                         m["shapes"]["sequence_length"]])
    lines.append(table(["control", "d_model", "layers", "heads", "lstm", "static",
                        "history", "context", "seq ch", "seq len"], body))
    lines.append("")

    lines += ["## Matched tree controls (same contract, same rows)", ""]
    import pandas as pd

    tree_rows = []
    for run in current:
        contract_dir = Path(run["contract_dir"])
        metrics = contract_dir / "tree_control" / "tree_control_metrics.csv"
        if not metrics.exists():
            continue
        df = pd.read_csv(metrics)
        for (split, arm), block in df.groupby(["split_id", "arm"]):
            # best *full-mode* neural model for this split, across all current runs
            candidates = [(r["control"], r["overall"]["rmse_sgd"], run.get("mode"))
                          for other in current
                          for r in other.get("results", [])
                          if r["split"] == split and other.get("mode") == "full"]
            best = min(candidates, key=lambda c: c[1]) if candidates else None
            tree_rows.append([split, arm, fmt(float(block["rmse_sgd"].iloc[0])),
                              fmt(float(block["mae_sgd"].iloc[0])),
                              int(block["n_validation"].iloc[0]),
                              f"{best[0]} {best[1]:.2f}" if best else "not run",
                              f"{best[1] - block['rmse_sgd'].iloc[0]:+.2f}" if best else "—"])
        break        # the tree artifact is per contract, not per run
    if tree_rows:
        lines.append(table(["split", "tree arm", "tree RMSE", "tree MAE", "n",
                            "best neural (full)", "neural − tree"], tree_rows))
        lines.append("")
        lines.append("Tree numbers come from the contract owner's `tree_control/` artifacts and "
                     "use the same sample rows, targets and months. `neural − tree` negative "
                     "means the neural model is better. Each split appears once per tree arm.")
        lines.append("")
    else:
        lines += ["No tree-control artifacts found in the current contract.", ""]

    lines += ["## Checkpoint verification", ""]
    body = []
    for run in current:
        for check in run.get("checkpoint_verification", []):
            body.append([run["run_id"], check["control"], check["seed"],
                         "ok" if check.get("ok") else "FAIL",
                         check.get("max_abs_delta_sgd")])
    lines.append(table(["run_id", "control", "seed", "result", "max |Δ| SGD"], body)
                 if body else "No checkpoint verification requested in these runs.")
    lines.append("")

    lines += ["## Not run", ""]
    splits_done = {r["split"] for run in current for r in run.get("results", [])}
    modes_done = {run.get("mode") for run in current}
    seeds_done = {r["seed"] for run in current for r in run.get("results", [])}
    body = []
    for split in ("orig", "early", "long"):
        for control in CONTROLS:
            hit = [run for run in current if run.get("mode") == "full"
                   and any(r["split"] == split and r["control"] == control
                           for r in run.get("results", []))]
            body.append([split, control, "yes" if hit else "NOT RUN",
                         sorted({r["seed"] for run in hit for r in run["results"]}) or "—"])
    lines.append(table(["split", "control", "full-mode run", "seeds"], body))
    lines.append("")
    lines.append(f"Splits with any run: {sorted(splits_done)}. Modes run: {sorted(modes_done)}. "
                 f"Seeds run: {sorted(seeds_done)}.")
    lines.append("")

    (REPORT_ROOT / "RESULTS.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote RESULTS.md from {len(current)} current-contract run(s), "
          f"{len(stale)} superseded, {len(runs) - len(complete)} incomplete")


if __name__ == "__main__":
    main()
