def verify(result):
    import re
    checks=[]
    for relative in ['reports/experiments/report_selection/FINAL_MODEL.md',
        'reports/experiments/report_selection/REPORT.md','reports/experiments/tenth_wave/README.md']:
        path=ROOT/relative;body=path.read_text(encoding='utf-8');assert '\ufffd' not in body
        count=0
        for target in re.findall(r'\]\(([^)]+)\)',body):
            if target.startswith(('http','#','mailto')):continue
            target=target.split('#')[0]
            if target:assert (path.parent/target).exists(),(relative,target);count+=1
        checks.append({'file':relative,'local_links_checked':count,'sha256':sha256(path)})
    for item in result['candidates']:assert sha256(ROOT/item['path'])==item['sha256']
    assert sha256(ROOT/result['final_copy'])==result['recommended_final']['sha256']
    final_text=(REPORT/'FINAL_MODEL.md').read_text(encoding='utf-8')
    for item in result['candidates']:
        for key,precision in [('local_annual_rmse',4),('local_recent_rmse',4),('kaggle_displayed_score',5)]:
            assert f'{item[key]:.{precision}f}' in final_text
    write_json(REPORT/'FINAL_SELECTION_VERIFICATION.json',{'files':checks,'numeric_cells_checked':9,
        'prediction_files_checked':3,'final_copy_hash_matched':True,'no_new_training_or_upload':True})


