"""Record screenshot scores, recommend a final, and reconcile report results."""
from __future__ import annotations
import json
import shutil
from pathlib import Path
import numpy as np
import pandas as pd
from analysis.experiments.frontier_search import ROOT,write_json
from analysis.pipeline.data import sha256

REPORT=ROOT/'reports/experiments/report_selection'
READY=ROOT/'output/submissions/ready_to_upload'
SCORES={'kaggle_best_history.csv':415.86912,'kaggle_best_macro.csv':415.78232,
    'kaggle_structure_blend.csv':415.37529}


def read(path):return json.loads((ROOT/path).read_text(encoding='utf-8'))


def run():
    history=read('reports/experiments/report_selection/best_ensemble.json')
    macro_annual=read('reports/experiments/fourth_wave/given_ensemble_outer.json')['versions']['conservative']['rmse_sgd']
    macro_recent=read('reports/experiments/fourth_wave/given_ensemble_june.json')['versions']['conservative']['rmse_sgd']
    structure=read('output/submissions/tenth_wave_structures/summary.json')
    old_manifest=read('output/submissions/ready_to_upload/submission_manifest.json')
    digest={Path(item['file']).name:item['sha256'] for item in old_manifest['files']}
    digest['kaggle_structure_blend.csv']=structure['sha256']
    descriptions=[('kaggle_best_history.csv','历史特征主融合','主基线',history['annual']['rmse_sgd'],history['recent']['rmse_sgd']),
        ('kaggle_best_macro.csv','比赛所给宏观增强','宏观消融',macro_annual,macro_recent),
        ('kaggle_structure_blend.csv','分组融合＋PLR-FT','推荐final',structure['local_annual_rmse'],structure['local_recent_rmse'])]
    records=[]
    for filename,method,role,annual,recent in descriptions:
        path=READY/filename;frame=pd.read_csv(path)
        assert len(frame)==50000 and list(frame)==['Id','Predicted']
        np.testing.assert_array_equal(frame.Id,np.arange(50000))
        assert np.isfinite(frame.Predicted).all() and sha256(path)==digest[filename]
        records.append({'file':filename,'path':str(path.relative_to(ROOT)).replace('\\','/'),
            'method':method,'report_role':role,'local_annual_rmse':annual,'local_recent_rmse':recent,
            'kaggle_displayed_score':SCORES[filename],'sha256':digest[filename],'rows':50000})
    final=min(records,key=lambda item:item['kaggle_displayed_score'])
    assert final['file']=='kaggle_structure_blend.csv'
    destination=ROOT/'output/submissions/final';destination.mkdir(parents=True,exist_ok=True)
    final_path=destination/'submission.csv';shutil.copy2(ROOT/final['path'],final_path)
    assert sha256(final_path)==final['sha256']
    evidence={'source':'User-provided Kaggle submission-list screenshot in this conversation',
        'observed_on':'2026-11-05','precision':'5 decimal places','leaderboard_partition':None,
        'source_note':'The screenshot shows filename and displayed score, but does not label public/private split. No API verification or new upload by the assistant.'}
    result={'recommended_final':final,'final_copy':'output/submissions/final/submission.csv',
        'candidates':records,'evidence':evidence,
        'improvement_vs_history':round(SCORES['kaggle_best_history.csv']-SCORES[final['file']],5),
        'improvement_vs_macro':round(SCORES['kaggle_best_macro.csv']-SCORES[final['file']],5),
        'kaggle_ui_final_selection_performed_by_assistant':False,
        'selection_scope':'Best of these three submitted candidates by the screenshot score, supported by lower local annual/recent errors than the other two. Not a claim of independent-test significance or unknown private-score optimality.'}
    write_json(REPORT/'FINAL_SELECTION.json',result)
    write_json(destination/'manifest.json',result)
    pd.DataFrame(records).to_csv(REPORT/'final_submission_comparison.csv',index=False)
    # Latest handoff manifests track user feedback; prediction files stay fixed.
    for item in old_manifest['files']:
        name=Path(item['file']).name
        item['actual_kaggle_score']=SCORES[name]
    old_manifest.update(uploaded=True,uploaded_by='user',score_evidence=evidence,
        note='Files generated by the assistant and subsequently submitted by the user. Scores come from the supplied screenshot; no fixed local-to-Kaggle offset is assumed.')
    write_json(READY/'submission_manifest.json',old_manifest)
    for path in [READY/'tenth_wave_submission_manifest.json',ROOT/'output/submissions/tenth_wave_structures/summary.json']:
        item=json.loads(path.read_text(encoding='utf-8'))
        item.update(actual_kaggle_score=SCORES[final['file']],uploaded=True,uploaded_by='user',score_evidence=evidence)
        write_json(path,item)
    summary_path=ROOT/'reports/experiments/tenth_wave/summary.json'
    summary=json.loads(summary_path.read_text(encoding='utf-8'))
    summary['export'].update(actual_kaggle_score=SCORES[final['file']],uploaded=True,uploaded_by='user',score_evidence=evidence)
    write_json(summary_path,summary)
    write_report(result)
    reconcile_documents(result)
    verify(result)
    print(json.dumps({'selected':final['file'],'score':SCORES[final['file']],
        'improvement_vs_history':result['improvement_vs_history'],
        'improvement_vs_macro':result['improvement_vs_macro'],'final_copy':result['final_copy']},ensure_ascii=False))


